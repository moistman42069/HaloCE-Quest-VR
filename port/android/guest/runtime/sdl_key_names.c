const char *SDL_GetScancodeName(SDL_Scancode code)
{
    return code >= SDL_SCANCODE_UNKNOWN && code < SDL_SCANCODE_COUNT && SDL_scancode_names[code]
        ? SDL_scancode_names[code] : "";
}
SDL_Scancode SDL_GetScancodeFromName(const char *name)
{
    unsigned i;
    if (!name || !*name) return SDL_SCANCODE_UNKNOWN;
    for (i=0; i<SDL_SCANCODE_COUNT; i++)
        if (SDL_scancode_names[i] && !strcasecmp(name, SDL_scancode_names[i])) return (SDL_Scancode)i;
    return SDL_SCANCODE_UNKNOWN;
}
